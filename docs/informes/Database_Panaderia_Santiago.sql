-- =========================================================
--
-- SINTAXIS DEL DOCUMENTO
--   Los comentarios que empiezan por `-- NUEVA` o `-- MODIFICADA` señalan
--   tablas y columnas que se agregaron o cambiaron al implementar los casos de
--   uso. Sirven para que la revisión distinga de un vistazo lo que es diseño
--   original de lo que agregado el equipo durante el desarrollo.
--
-- NOTA SOBRE LAS LLAVES PRIMARIAS
--   Las PK de las tablas del módulo de Usuarios y Seguridad usan
--   `GENERATED BY DEFAULT AS IDENTITY`. Es lo que realmente genera Django y lo
--   que evita el error "duplicate key value violates unique constraint" al
--   insertar sin especificar el id.
--
-- NOTA SOBRE LAS LLAVES FORÁNEAS
--   Todas las FK van `DEFERRABLE INITIALLY DEFERRED`, que es lo que emite
--   Django. La diferencia importa: con `INITIALLY IMMEDIATE` la FK se valida en
--   cada sentencia y no se puede reordenar un INSERT que referencie una fila
--   que todavia no existe en la misma transaccion. Con DEFERRED, PostgreSQL
--   valida todas las FK al final, y por eso se pueden cargar tablas que se
--   referencian entre si en cualquier orden.
-- =========================================================



CREATE TABLE "rol" (
  "id_rol" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre" varchar(50) UNIQUE NOT NULL,
  "descripcion" text
);

-- MODIFICADA (CU4): se agrega columna `modulo` varchar(30) NOT NULL con valor
-- por defecto 'usuarios_seguridad' para agrupar los permisos según los 5 paquetes
-- del backend (PACKAGE_CU_MAP.md) y estructurar la matriz de permisos.
CREATE TABLE "permiso" (
  "id_permiso" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre" varchar(50) UNIQUE NOT NULL,
  "descripcion" text,
  "modulo" varchar(30) NOT NULL DEFAULT 'usuarios_seguridad'
);

-- ALINEADA (CU4):
-- Se resuelve la deriva documentada en CU3 alineando el DDL a la arquitectura estándar
-- de Django. La tabla utiliza una clave primaria subrogada `id` y una restricción
-- UNIQUE compuesta ("id_rol", "id_permiso"), garantizando exactamente la misma regla de
-- negocio ("un rol no repite el mismo permiso") sin forzar claves primarias compuestas
-- experimentales en el ORM.
CREATE TABLE "rol_permiso" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_rol" bigint NOT NULL,
  "id_permiso" bigint NOT NULL,
  CONSTRAINT "rol_permiso_unico" UNIQUE ("id_rol", "id_permiso")
);

-- MODIFICADA (CU1): se le agregan las 3 columnas de control de bloqueo por
-- intentos fallidos, mas `is_staff`, `is_superuser` y `last_login` que Django
-- exige en su clase base de usuario.
--   intentos_fallidos      contador de fallos consecutivos. El CHECK impide que
--                          sea negativo, aunque la logica nunca lo seria.
--   bloqueado_hasta        instante en que expira la ventana de bloqueo. NULL
--                          significa que la cuenta NO esta bloqueada, y es el
--                          unico estado que la logica consulta para decidir.
--   ultimo_intento_fallido cuando ocurrio el ultimo fallo. Permite detectar un
--                          ataque en curso aunque todavia no haya bloqueo.
-- MODIFICADA (CU2): `email` pasa de NULL a NOT NULL, porque es el canal por el
-- que sale el enlace de recuperacion. Sin correo, el CU2 no tiene a donde
-- escribir. La unicidad va sobre `Lower("email")` y no sobre la columna, para
-- que "Persona@mail.com" y "persona@mail.com" no sean dos cuentas distintas
-- (ver el indice unico mas abajo).
-- NOTA (CU3): `nombre_usuario` conserva su `UNIQUE` de columna, pero la
-- garantia real de que no haya dos cuentas que solo difieran en mayusculas la
-- da el indice `usuario_username_unico_ci` de mas abajo. Ver el comentario de
-- ese indice antes de concluir nada leyendo solo la definicion de la columna.
CREATE TABLE "usuario" (
  "id_usuario" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_rol" bigint,
  "nombre_usuario" varchar(50) UNIQUE NOT NULL,
  "hash_contrasena" varchar(255) NOT NULL,
  "nombre_completo" varchar(150) NOT NULL,
  "email" varchar(150) NOT NULL,
  "activo" boolean NOT NULL DEFAULT true,
  "is_staff" boolean NOT NULL DEFAULT false,
  "is_superuser" boolean NOT NULL DEFAULT false,
  "last_login" timestamp with time zone,
  "intentos_fallidos" smallint NOT NULL DEFAULT 0
    CONSTRAINT "usuario_intentos_fallidos_no_negativo" CHECK ("intentos_fallidos" >= 0),
  "bloqueado_hasta" timestamp with time zone,
  "ultimo_intento_fallido" timestamp with time zone
);

-- NUEVO (CU2) - Unicidad del correo sin distinguir mayusculas.
-- Un UNIQUE sobre la columna no alcanzaria: PostgreSQL compara "Persona@mail.com"
-- y "persona@mail.com" como dos valores distintos, asi que las dos cuentas
-- coexistirian y la recuperacion de contrasena quedaria ambigua.
-- El nombre lleva el sufijo "_ci" (case insensitive) para que quede claro al
-- leer el esquema que la comparacion no distingue mayusculas.
CREATE UNIQUE INDEX "usuario_email_unico_ci" ON "usuario" (Lower("email"));

-- NUEVO (CU3) - Unicidad del nombre de usuario sin distinguir mayusculas.
--
-- Por que hace falta si arriba ya dice UNIQUE: porque el UNIQUE de columna en
-- PostgreSQL significa "unico y DISTINTO DE MAYUSCULAS". Con solo eso, "Admin"
-- y "admin" coexistian como dos cuentas validas, y como el login resuelve por
-- coincidencia exacta (`nombre_usuario = <lo que se escribio>`), una de las dos
-- quedaba permanentemente inaccesible. El Administrador veia una cuenta
-- "creada correctamente" que nadie podia usar, sin ninguna pista de por que.
--
-- Por que conviven los dos indices y no se elimina el UNIQUE de la columna:
-- Django exige por contrato (auth.E003) que el campo USERNAME_FIELD de un
-- modelo de usuario sea unico. Quitarlo rompe el sistema de autenticacion
-- entero, y silenciar esa verificacion con SILENCED_SYSTEM_CHECKS seria
-- esconder un problema real en lugar de resolverlo. El UNIQUE de columna queda
-- como el indice que usa la busqueda del login; este es el que decide si dos
-- cuentas pueden llamarse igual.
CREATE UNIQUE INDEX "usuario_username_unico_ci"
  ON "usuario" (Lower("nombre_usuario"));

-- MODIFICADA (CU1):
--   id_usuario  dejo de ser NOT NULL y su FK paso a ON DELETE SET NULL. Un
--               intento de acceso fallido ocurre justamente cuando NADIE esta
--               autenticado, asi que la bitacora debe poder registrarlo sin
--               usuario. Con ON DELETE SET NULL, borrar un usuario conserva su
--               historial de auditoria en vez de destruirlo.
--   accion      ahora esta controlada por el enum AccionBitacora del codigo
--               Python, para que una errata falle al escribirse y no cree en
--               silencio una categoria que ningun reporte agrupa.
-- NUEVAS (CU1):
--   nombre_usuario_intento  nombre digitado en un intento fallido, para poder
--                           correlacionar sin tener usuario autenticado.
--   agente_usuario          User-Agent del navegador. Junto con la IP
--                           distingue a una persona de un bot automatico.
-- MODIFICADA (CU3): `accion` sigue siendo `varchar(50)` —NO es un enum de
-- PostgreSQL ni una tabla de lookup— y su lista de valores admitidos crece en
-- el codigo Python (`AccionBitacora`). Por eso la migracion 0006 no altera ni
-- un byte de los registros que ya existen: agrega cuatro claves.
--     ALTA_USUARIO              alta de una cuenta
--     EDICION_USUARIO           modificacion de datos de una cuenta
--     CAMBIAR_ESTADO_USUARIO    activacion o inactivacion
--     RESTABLECER_CONTRASENA    reset administrativo de clave
-- `DESBLOQUEO_CUENTA`, que CU3 tambien usa al desbloquear una cuenta, ya
-- existia desde CU1 y se reutiliza tal cual. Partirla en dos habria dividido un
-- mismo hecho en dos filas de reporte.
CREATE TABLE "bitacora" (
  "id_bitacora" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_usuario" bigint,
  "nombre_usuario_intento" varchar(50),
  "agente_usuario" varchar(255),
  "accion" varchar(50) NOT NULL,
  "tabla_afectada" varchar(50),
  "descripcion" text,
  "fecha_hora" timestamp NOT NULL DEFAULT (now())
);

-- NUEVA (CU1) - Politica de bloqueo por intentos fallidos.
-- Fila unica: la clave primaria fija en 1, reforzada con un CHECK que impide
-- que exista una segunda fila. El umbral NO vive en settings.py precisely para
-- que el Administrador pueda cambiarlo sin desplegar.
-- Los dos CHECK de rango tambien evitan el error tonto de guardar 0 intentos
-- (dejaria la cuenta bloqueada siempre) o 0 minutos (bloqueo instantaneo).
-- MODIFICADA (CU2): se agregan los 3 parametros de la recuperacion de
-- contrasena, con el mismo criterio que los dos de CU1: el umbral lo decide el
-- Administrador desde el panel, no el equipo con un redeploy. Por eso viven en
-- la base y no en settings.py.
--   minutos_expiracion_token  vigencia del enlace de recuperacion.
--   max_intentos_token        cuantas confirmaciones admite un mismo enlace antes
--                             de quemarlo. Frena a quien robo un enlace y prueba
--                             contrasenas al azar.
--   max_solicitudes_por_hora   cuantos enlaces puede pedir una misma cuenta por
--                             hora. Protege el buzon del usuario.
CREATE TABLE "configuracion_seguridad" (
  "id_configuracion" smallint NOT NULL DEFAULT 1
    CONSTRAINT "configuracion_seguridad_singleton" CHECK ("id_configuracion" = 1),
  "max_intentos_fallidos" smallint NOT NULL DEFAULT 3
    CONSTRAINT "configuracion_seguridad_rango_intentos"
      CHECK ("max_intentos_fallidos" BETWEEN 1 AND 20),
  "minutos_bloqueo" integer NOT NULL DEFAULT 10
    CONSTRAINT "configuracion_seguridad_rango_minutos"
      CHECK ("minutos_bloqueo" BETWEEN 1 AND 1440),
  "actualizado_en" timestamp with time zone NOT NULL DEFAULT (now()),
  "actualizado_por_id" bigint,
  "minutos_expiracion_token" smallint NOT NULL DEFAULT 15
    CONSTRAINT "configuracion_seguridad_rango_expiracion_token"
      CHECK ("minutos_expiracion_token" BETWEEN 1 AND 1440),
  "max_intentos_token" smallint NOT NULL DEFAULT 5
    CONSTRAINT "configuracion_seguridad_rango_intentos_token"
      CHECK ("max_intentos_token" BETWEEN 1 AND 20),
  "max_solicitudes_por_hora" smallint NOT NULL DEFAULT 3
    CONSTRAINT "configuracion_seguridad_rango_solicitudes_hora"
      CHECK ("max_solicitudes_por_hora" BETWEEN 1 AND 20)
);
-- Nota: Django agrega ademas un CHECK ">= 0" por cada campo declarado como
-- PositiveSmallIntegerField. Son redundantes con los CHECK con nombre de arriba
-- y no se reproducen aqui para no ensuciar el DDL.

-- NUEVAS (CU1) - Lista negra de tokens JWT.
-- Las crea la app `rest_framework_simplejwt.token_blacklist` de Django. Se
-- declaran aqui para que el modelo fisico este completo. Sin estas dos tablas
-- el logout NO revocaria nada: el refresh token seguiria valido hasta cumplir
-- sus 7 dias, y la rotacion de tokens dejaria inservible al propio usuario.
CREATE TABLE "token_blacklist_outstandingtoken" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "token" text NOT NULL,
  "created_at" timestamp with time zone NOT NULL,
  "user" bigint NOT NULL,
  "jti" varchar(255) NOT NULL
);

CREATE TABLE "token_blacklist_blacklistedtoken" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "token" text NOT NULL,
  "created_at" timestamp with time zone NOT NULL,
  "expires_at" timestamp with time zone NOT NULL
);



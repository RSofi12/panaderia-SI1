-- NUEVA (CU2) - Enlaces de recuperacion de contrasena.
--
-- LA REGLA MAS IMPORTANTE DE ESTA TABLA: aqui NO se guarda el token. Se guarda
-- `token_hash`, que es el SHA-256 del token de 20 caracteres. El token en claro
-- sale unicamente por correo y existe en la RAM del proceso el instante en que
-- se genera. Si alguien lee esta tabla (un dump, un backup, una consulta del
-- Administrador) no tiene nada que clicksar.
--
-- El hash SHA-256 alcanza porque el token tiene ~100 bits de entropia: no hay
-- diccionario que atacar, asi que no hacen falta ni salt ni un algoritmo lento
-- tipo bcrypt. Con un codigo de 6 digitos el hash no habria servido de nada,
-- porque las 10^6 combinaciones se enumeran en un rato.
--
--   token_hash     SHA-256 hexadecimal (64 caracteres). UNIQUE: es por este
--                  valor por donde se busca, nunca por el token en claro.
--   email_destino   copia del correo en el momento de pedir el enlace. Si el
--                  usuario cambia su correo a mitad de camino, el enlace sigue
--                  siendo auditable aunque ya no apunte a la casilla actual.
--   creado_en       emision del enlace.
--   expira_en       vence por tiempo. El CHECK impide que se cargue una fila
--                  con la expiracion antes del alta.
--   usado_en        se pone cuando el enlace se consume con exito. Un enlace es
--                  de un SOLO uso.
--   invalidado_en   se pone cuando el enlace muere sin usarse: porque el usuario
--                  pidió otro, porque se agotaron los intentos, o por la purga
--                  de vencidos. NULL = el enlace sigue vivo.
--   intentos        confirmaciones ya consumidas contra este enlace. El tope lo
--                  fija `configuracion_seguridad.max_intentos_token`.
--   ip_origen       hasta 45 caracteres: cabe la IPv6 larga con su prefijo.
--   agente_usuario  User-Agent del navegador, truncado a 255.
--
-- `usado_en` y `invalidado_en` son los dos "muertes" posibles de un enlace, y
-- se guardan por separado a proposito: el informe de CU26 necesita distinguir
-- "el usuario completo el proceso" de "el enlace murio solo".
CREATE TABLE "token_recuperacion" (
  "id_token" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "token_hash" varchar(64) NOT NULL UNIQUE,
  "email_destino" varchar(150) NOT NULL,
  "creado_en" timestamp with time zone NOT NULL DEFAULT (now()),
  "expira_en" timestamp with time zone NOT NULL,
  "usado_en" timestamp with time zone,
  "invalidado_en" timestamp with time zone,
  "intentos" smallint NOT NULL DEFAULT 0
    CONSTRAINT "token_recuperacion_intentos_no_negativos" CHECK ("intentos" >= 0),
  "ip_origen" varchar(45),
  "agente_usuario" varchar(255),
  "usuario_id" bigint NOT NULL,
  CONSTRAINT "token_recuperacion_expiracion_positiva"
    CHECK ("expira_en" > "creado_en"),
  CONSTRAINT "token_recuperacion_uso_coherente"
    CHECK ("usado_en" IS NULL OR "usado_en" >= "creado_en")
);

-- Indice compuesto para la consulta de la cuota por hora, que cuenta los
-- enlaces que el usuario emitio en la ultima hora. El orden descendente en
-- `creado_en` hace que PostgreSQL pueda recorrer el indice desde el final, que
-- es justo la parte que interesa.
CREATE INDEX "token_recuperacion_usuario_idx"
  ON "token_recuperacion" ("usuario_id", "creado_en" DESC);

-- La FK va con ON DELETE CASCADE a proposito: si se borra la cuenta, sus
-- enlaces deben morir con ella. Un token huerfano apuntando a un usuario
-- inexistente permitiria reiniciar el reloj de un enlace viejo. La cascada se
-- puso con la migracion `recuperacion.0002_fk_token_recuperacion_cascade`,
-- porque Django NO la habia aplicado por su cuenta (para su editor de esquemas
-- `on_delete` no es un parametro de base de datos y la emite como no-op).
ALTER TABLE "token_recuperacion"
  ADD CONSTRAINT "token_recuperacion_usuario_id_fk"
  FOREIGN KEY ("usuario_id") REFERENCES "usuario"("id_usuario")
  ON DELETE CASCADE
  DEFERRABLE INITIALLY DEFERRED;


